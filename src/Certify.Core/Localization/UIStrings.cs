    public static bool IsSupported(string? code) => code != null && Languages.Any(l => l.Code == code);

    public static bool IsRightToLeft(string lang) => lang is "ar" or "fa";

    /// <summary>Auto -> jezyk systemu, jesli obslugiwany (inaczej en); reczny wybor wprost.</summary>
    public static string ResolveLang(string setting, string osTwoLetter)
    {
        if (IsSupported(setting)) return setting;
        return IsSupported(osTwoLetter) ? osTwoLetter : "en";
    }

    public static IEnumerable<string> Keys => S.Keys;

    public static bool Has(string key) => S.ContainsKey(key);

    public static string T(string key, params object?[] args)
    {
        if (!S.TryGetValue(key, out var pair)) return key;
        var template = Lang switch
        {
            "pl" => pair.Pl,
            "en" => pair.En,
            _ => Translation(Lang).GetValueOrDefault(key) ?? pair.En,
        };
        if (string.IsNullOrEmpty(template) && Lang != "pl") template = pair.Pl; // fallback
        try
        {
            return args.Length == 0 ? template : string.Format(System.Globalization.CultureInfo.InvariantCulture, template, args);
        }
        catch { return template; }
    }

    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, IReadOnlyDictionary<string, string>> Translations = new();

    /// <summary>Tlumaczenia jezyka spoza PL/EN (pusty slownik, gdy brak pliku).</summary>
    public static IReadOnlyDictionary<string, string> Translation(string lang) =>
        Translations.GetOrAdd(lang, static l =>
        {
            using var stream = typeof(UIStrings).Assembly.GetManifestResourceStream($"Certify.Core.Localization.Translations.{l}.json");
            if (stream == null) return new Dictionary<string, string>();
            return System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(stream) ?? new Dictionary<string, string>();
        });

