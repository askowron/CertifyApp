    /// <summary>
    /// Obslugiwane jezyki (kod ISO 639-1, nazwa natywna): 20 najpopularniejszych
    /// jezykow tresci w internecie (ranking W3Techs), w tym polski.
    /// </summary>
    public static IReadOnlyList<(string Code, string Name)> Languages { get; } =
    [
        ("en", "English"),
